// Workflow engine: each flow also becomes a Claude Code workflow script
// (.claude/workflows/<prefix><flow>.js) that runs it deterministically. The script is the
// flow's data (as JSON) followed by the shared runtime in engines/workflow/runtime.js.
// Enabled per project with `engines: [skill, workflow]`.
import path from 'node:path';
import { GENERATOR, KERNEL_VERSION } from './kernel.mjs';
import { readText } from './load.mjs';
import { getContract } from './validate.mjs';

export const WORKFLOW_RUNTIME = path.join('engines', 'workflow', 'runtime.js');

// JSON Schema for agent(schema): plain, without the meta keys.
function plainSchema(schema) {
  const { $schema, $id, title, ...rest } = schema;
  return JSON.parse(JSON.stringify(rest));
}

const agentsOfStep = (s) => (s.loop ? s.loop.steps.flatMap(agentsOfStep) : s.fanout ?? [s.agent]);

// -> { path, content } or null. `agents` maps agent id -> { produces, enabled }.
export async function renderWorkflow(flow, agents, ws, diags, stackRoot) {
  const runtimeFile = path.join(stackRoot, WORKFLOW_RUNTIME);
  const runtime = await readText(runtimeFile);
  if (runtime === null) {
    diags.error('missing-file', `workflow runtime not found (${WORKFLOW_RUNTIME})`, runtimeFile);
    return null;
  }
  const prefix = ws.config.prefix ?? '';
  const data = flow.data;

  const used = {};
  const contracts = {};
  for (const step of data.steps) {
    const external = step.external || false;
    for (const id of agentsOfStep(step)) {
      if (external || used[id]) continue;
      const agent = agents.get(id);
      if (!agent) continue; // the skill engine already reported it
      used[id] = { type: `${prefix}${id}`, produces: agent.produces ?? null };
      if (agent.produces && !contracts[agent.produces]) contracts[agent.produces] = plainSchema(getContract(agent.produces));
    }
  }

  const name = `${prefix}${flow.id}`;
  const meta = {
    name,
    description: String(data.description).trim().split(/(?<=\.)\s/)[0],
    whenToUse: `Deterministic, unattended run of the ${name} flow; started by /${name} --workflow.`,
    phases: data.steps.map((s) => ({ title: s.id })),
  };
  const content = [
    `// generated by ${GENERATOR} (kernel ${KERNEL_VERSION}) from flow "${flow.id}". Do not edit: change the modules or project.yaml, then run stack build.`,
    `export const meta = ${JSON.stringify(meta, null, 2)}`,
    '',
    `const FLOW = ${JSON.stringify({ id: flow.id, steps: data.steps }, null, 2)}`,
    `const AGENTS = ${JSON.stringify(used, null, 2)}`,
    `const HANDOFF = ${JSON.stringify(plainSchema(getContract('handoff')), null, 2)}`,
    `const CONTRACTS = ${JSON.stringify(contracts, null, 2)}`,
    `const REPORT = ${JSON.stringify(String(data.report ?? '').trim())}`,
    '',
    runtime.trim(),
    '',
  ].join('\n');
  return { path: `workflows/${name}.js`, content };
}
